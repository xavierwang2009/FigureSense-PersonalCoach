// Run: node tests/ui-flow.cjs
const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const path = require('node:path');
const harness = { require, __dirname, console, setTimeout() {} };
vm.createContext(harness);
vm.runInContext(fs.readFileSync(path.join(__dirname, 'point-controls.cjs'), 'utf8')
  .split('const {state, nearestPoint')[0] + '\nglobalThis.app=sandbox;globalThis.el=element;', harness);
const { app, el } = harness;
let loaded = 0, destination;
app.window.confirm = () => false;
vm.runInContext('loadClip=()=>{ globalThis.loadedDemo(); }; renderResults=()=>{};', app);
app.loadedDemo = () => loaded++;
el('demoClip').handlers.click();
assert.equal(loaded, 0, 'cancelling the demo preserves the unfinished review');
assert(app.controls.state.drafts.first.frame);
app.window.confirm = () => true;
app.document.querySelector = () => null;
el('demoClip').handlers.click();
assert.equal(loaded, 1, 'confirming loads the demo');
app.CustomEvent = class { constructor(type, options) { this.type = type; this.detail = options.detail; } };
app.document.dispatchEvent = event => { destination = event.detail; };
el('startOver').handlers.click();
assert.equal(destination, undefined, 'first click only asks for confirmation');
assert(app.controls.state.drafts.first.frame);
el('startOver').handlers.click();
assert.equal(Object.keys(app.controls.state.drafts).length, 0);
assert.equal(destination, 'setup', 'confirmed new review returns to figure selection');
console.log('PASS: demo cancellation, demo confirmation, and new-review navigation');
